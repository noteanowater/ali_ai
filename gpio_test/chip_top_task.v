// ----------------------------------------------------------------------------
// Wait / pad / interrupt-line checks (no register access in here)
// ----------------------------------------------------------------------------
task gpio_wait_clk;
input integer n;
integer k;
begin
    for (k = 0; k < n; k = k + 1) @(posedge `GPIO_PCLK);
    #1;
end
endtask

task gpio_chk_pad_mask;
input [127:0]    exp;
input [127:0]    mask;
input [8*48:1]   tag;
integer          k;
begin
    if (((gpio_pad_obs ^ exp) & mask) !== 128'b0)
        for (k = 0; k < 111; k = k + 1)
            if (mask[k] && (gpio_pad_obs[k] !== exp[k])) begin
                gpio_err_cnt = gpio_err_cnt + 1;  gpio_pad_err_cnt = gpio_pad_err_cnt + 1;
                $display("    at %t, Error : %0s : GPIO_%0d pad %0s = %b, expect %b",
                         $time, tag, k, gpio_pad_name(k), gpio_pad_obs[k], exp[k]);
            end
end
endtask

task gpio_chk_pad;
input [127:0]    exp;
input [8*48:1]   tag;
begin
    gpio_chk_pad_mask(exp, GPIO_OUT_CHK, tag);
end
endtask

task gpio_chk_intr_line;
input            exp;
input [8*48:1]   tag;
begin
`ifdef GPIO_INTR_SIG
    if (`GPIO_INTR_SIG !== exp) begin
        gpio_err_cnt = gpio_err_cnt + 1;  gpio_intr_err_cnt = gpio_intr_err_cnt + 1;
        $display("    at %t, Error : %0s : gpio_intr = %b, expect %b", $time, tag, `GPIO_INTR_SIG, exp);
    end
`endif
end
endtask

