#!/usr/bin/env python3
"""Generate gpio_pad_map.vh from the HS100 PinPad spreadsheet.

Usage:
    python3 gen_gpio_pad_map.py HS100_PinPad.xlsx [--fmt "test_chip_top.{pin}"] [-o gpio_pad_map.vh]

The "GPIO" column (FUNCTION GPIO, SELECT = *_SEL_000) of sheet "Pin_Pad" gives the
GPIO channel number of each pad.  --fmt is the hierarchical net name of the pad in
the testbench; {pin} is replaced by the Pin Name column (e.g. XLSYNC3).
"""
import argparse
import re
import sys

import openpyxl

GPIO_TOTAL = 111  # GPIO_0 .. GPIO_110

# Column index (0-based) in sheet Pin_Pad
C_PADNO, C_LOC, C_PIN, C_TYPE, C_IO = 3, 4, 5, 6, 8
C_STRAP, C_STRAPV = 19, 20
C_GPIO, C_GPIO_SEL = 45, 47
C_ES = 48


def load(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb["Pin_Pad"]
    hdr = [c.value for c in ws[1]]
    if hdr[C_GPIO] != "GPIO" or hdr[C_PIN] != "Pin Name":
        sys.exit("unexpected Pin_Pad header layout: col%d=%r col%d=%r"
                 % (C_GPIO, hdr[C_GPIO], C_PIN, hdr[C_PIN]))
    m = {}
    for r in ws.iter_rows(min_row=2, max_col=C_ES + 1, values_only=True):
        g = r[C_GPIO]
        if not g:
            continue
        mo = re.fullmatch(r"GPIO_(\d+)", str(g).strip())
        if not mo:
            continue
        n = int(mo.group(1))
        if n in m:
            sys.exit("GPIO_%d appears twice (%s, %s)" % (n, m[n]["pin"], r[C_PIN]))
        m[n] = dict(pin=str(r[C_PIN]).strip(), padno=r[C_PADNO], loc=r[C_LOC],
                    type=r[C_TYPE], io=r[C_IO], strap=r[C_STRAP], strapv=r[C_STRAPV],
                    sel=r[C_GPIO_SEL], es=r[C_ES])
    return m


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("xlsx")
    ap.add_argument("--fmt", default="test_chip_top.{pin}")
    ap.add_argument("-o", "--out", default="gpio_pad_map.vh")
    a = ap.parse_args()

    m = load(a.xlsx)
    missing = [n for n in range(GPIO_TOTAL) if n not in m]

    L = []
    w = L.append
    w("// ==========================================================================")
    w("// gpio_pad_map.vh  --  AUTO-GENERATED by gen_gpio_pad_map.py, do not edit.")
    w("// Source : HS100_PinPad.xlsx / sheet Pin_Pad / column GPIO (SEL_000)")
    w("// Net fmt: %s" % a.fmt)
    w("// GPIO channels without a pad: %s" % (", ".join("GPIO_%d" % n for n in missing) or "none"))
    w("// ==========================================================================")
    w("//  GPIO     | Pin Name          | PadNo | Loc | Pad Type               | IO | Strap / ES")
    for n in sorted(m):
        d = m[n]
        note = []
        if d["strap"]:
            note.append("STRAP %s=%s" % (d["strap"], d["strapv"]))
        if d["es"]:
            note.append(str(d["es"]))
        w("//  GPIO_%-4d| %-18s| %-6s| %-4s| %-23s| %-3s| %s" % (
            n, d["pin"], d["padno"], d["loc"], d["type"], d["io"], ", ".join(note)))
    w("// ==========================================================================")
    w("")
    w("// Channels that physically exist on a pad (bit n = GPIO_n)")
    exist = 0
    for n in m:
        exist |= 1 << n
    w("wire [127:0] GPIO_PAD_EXIST  = 128'h%032x;" % exist)
    inonly = 0
    strap = 0
    for n, d in m.items():
        if str(d["io"]).strip().upper() == "I":
            inonly |= 1 << n
        if d["strap"]:
            strap |= 1 << n
    w("// Pads whose IO type is input-only (cannot be observed in output test)")
    w("wire [127:0] GPIO_PAD_INONLY = 128'h%032x;" % inonly)
    w("// Strap pads (sampled at reset)")
    w("wire [127:0] GPIO_PAD_STRAP  = 128'h%032x;" % strap)
    w("")
    w("// ---- Observe : pad value seen at chip boundary")
    w("wire [127:0] gpio_pad_obs;")
    for n in range(128):
        if n in m:
            w("assign gpio_pad_obs[%d] = %s;" % (n, a.fmt.format(pin=m[n]["pin"])))
    w("assign gpio_pad_obs[127:%d] = %d'b0;" % (GPIO_TOTAL, 128 - GPIO_TOTAL))
    for n in missing:
        w("assign gpio_pad_obs[%d] = 1'b0;" % n)
    w("")
    w("// ---- Drive : after gpio_pad_force_all, every change of gpio_pad_drv re-forces the pads")
    w("reg [127:0] gpio_pad_drv;")
    w("reg         gpio_pad_forced;")
    w("initial begin gpio_pad_drv = 128'b0; gpio_pad_forced = 1'b0; end")
    w("")
    w("task gpio_pad_apply;")
    w("begin")
    for n in sorted(m):
        w("    force %s = gpio_pad_drv[%d];" % (a.fmt.format(pin=m[n]["pin"]), n))
    w("end")
    w("endtask")
    w("")
    w("always @(gpio_pad_drv) if (gpio_pad_forced) gpio_pad_apply;")
    w("")
    w("task gpio_pad_force_all;")
    w("begin")
    w("    gpio_pad_forced = 1'b1;")
    w("    gpio_pad_apply;")
    w("end")
    w("endtask")
    w("")
    w("task gpio_pad_release_all;")
    w("begin")
    w("    gpio_pad_forced = 1'b0;")
    for n in sorted(m):
        w("    release %s;" % a.fmt.format(pin=m[n]["pin"]))
    w("end")
    w("endtask")
    w("")
    w("function [8*20:1] gpio_pad_name;")
    w("input integer n;")
    w("begin")
    w("    case (n)")
    for n in sorted(m):
        w("    %3d : gpio_pad_name = \"%s\";" % (n, m[n]["pin"]))
    w("    default : gpio_pad_name = \"<no pad>\";")
    w("    endcase")
    w("end")
    w("endfunction")
    w("")

    with open(a.out, "w") as f:
        f.write("\n".join(L))
    print("wrote %s : %d GPIO pads, missing %s" % (a.out, len(m), missing))


if __name__ == "__main__":
    main()
